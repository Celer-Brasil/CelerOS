Ppu* ppu_init(Snes* snes) {
  Ppu* ppu = (Ppu*) malloc(sizeof(Ppu));
  ppu->snes = snes;
  ppu->renderOn = true;
  ppu->palDirty = true;
  ppu->deferOn = true;
  ppu->snapCount = 0;
  ppu->snapBuf = NULL;  // ppu_setSnapBuffer (o blob aponta para a scratch)
  ppu->deferOn = false;
  ppu->outFb = NULL;
  ppu->lineSink = NULL;
  ppu->lineCtx = NULL;
  ppu_buildRankTable();
  return ppu;
}

